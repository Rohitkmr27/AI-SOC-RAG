@pytest.fixture
def sqlite_client() -> TestClient:
    engine = create_engine("sqlite://", connect_args={"check_same_thread": False}, poolclass=StaticPool)
    Base.metadata.create_all(engine)
    factory = sessionmaker(bind=engine)

    def override_db():
        with factory() as session:
            yield session

    app.dependency_overrides[get_db] = override_db
    with TestClient(app) as test_client:
        yield test_client
    app.dependency_overrides.clear()
    Base.metadata.drop_all(engine)


def test_api_enrich_alert_success(sqlite_client: TestClient, monkeypatch: pytest.MonkeyPatch) -> None:
    test_chunk = make_test_chunk()
    monkeypatch.setattr("app.rag.alert_enrichment.search_chunks", lambda **kwargs: [test_chunk])

    mock_llm = MockAnalystLLM()
    app.dependency_overrides[get_llm_provider] = lambda: mock_llm

    # Create alert in SQLite
    create_res = sqlite_client.post("/alerts", json={
        "timestamp": "2026-09-19T10:00:00Z",
        "source_ip": "192.0.2.10",
        "destination_ip": "198.51.100.20",
        "source_port": 51515,
        "destination_port": 443,
        "protocol": "TCP",
        "attack_type": "PortScan",
        "confidence": 0.91,
        "severity": "Medium",
        "description": "Network alert for testing enrichment.",
    })
    assert create_res.status_code == 201
    alert_id = create_res.json()["id"]

    # Call POST /alerts/{alert_id}/enrich
    enrich_res = sqlite_client.post(f"/alerts/{alert_id}/enrich")
    assert enrich_res.status_code == 200

    data = enrich_res.json()
    assert data["alert"]["id"] == alert_id
    assert data["alert"]["attack_type"] == "PortScan"
    assert "PortScan alert indicates systematic probe" in data["analysis"]["summary"]
    assert len(data["sources"]) == 1
    assert data["sources"][0]["chunk_id"] == "chunk_t1046"
    assert data["sources"][0]["score"] == pytest.approx(0.88)



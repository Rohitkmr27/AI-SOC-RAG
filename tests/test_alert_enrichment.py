def test_enrich_alert_success_with_mocked_llm(monkeypatch: pytest.MonkeyPatch) -> None:
    test_chunk = make_test_chunk()
    monkeypatch.setattr("app.rag.alert_enrichment.search_chunks", lambda **kwargs: [test_chunk])


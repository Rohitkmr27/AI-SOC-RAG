def test_parse_analyst_response_valid_json() -> None:
    alert = make_test_alert()
    raw = json.dumps({
        "summary": "Valid summary.",
        "observed_indicators": ["Ind 1"],
        "security_context": ["Ctx 1"],
        "investigation_steps": ["Step 1"],
        "recommended_mitigations": ["Mit 1"],
    })
    analysis = parse_analyst_response(raw, alert)

    assert analysis.summary == "Valid summary."
    assert analysis.observed_indicators == ["Ind 1"]
    assert analysis.security_context == ["Ctx 1"]
    assert analysis.investigation_steps == ["Step 1"]
    assert analysis.recommended_mitigations == ["Mit 1"]


def test_parse_analyst_response_handles_markdown_codeblock() -> None:
    alert = make_test_alert()
    raw = "```json\n" + json.dumps({
        "summary": "Codeblock summary.",
        "observed_indicators": ["Ind 2"],
    }) + "\n```"
    analysis = parse_analyst_response(raw, alert)

    assert analysis.summary == "Codeblock summary."
    assert analysis.observed_indicators == ["Ind 2"]


def test_parse_analyst_response_malformed_text_fallback() -> None:
    alert = make_test_alert()
    raw_text = "This is a plain text analyst note without JSON formatting. Port scan observed."
    analysis = parse_analyst_response(raw_text, alert)

    assert isinstance(analysis, AlertAnalysis)
    assert "plain text analyst note" in analysis.summary
    assert any("PortScan" in ind for ind in analysis.observed_indicators)
    assert len(analysis.investigation_steps) > 0



class MockAnalystLLM(LLMProvider):
    """Mock LLM that returns pre-configured JSON analysis."""

    def __init__(self, response_data: dict[str, Any] | str | None = None) -> None:
        if response_data is None:
            self.response_text = json.dumps({
                "summary": "PortScan alert indicates systematic probe against destination port 443.",
                "observed_indicators": [
                    "TCP SYN activity targeting port 443",
                    "High confidence model score (0.91)",
                ],
                "security_context": [
                    "MITRE ATT&CK T1046: Network Service Discovery",
                    "Adversaries scan ports to identify vulnerable listening services.",
                ],
                "investigation_steps": [
                    "Inspect firewall logs for packet bursts from source IP 192.0.2.10.",
                    "Verify if destination service responded with SYN-ACK or RST.",
                ],
                "recommended_mitigations": [
                    "Enforce rate-limiting on inbound perimeter interfaces.",
                    "Ensure unneeded exposed ports are closed.",
                ],
            })
        elif isinstance(response_data, dict):
            self.response_text = json.dumps(response_data)
        else:
            self.response_text = response_data

        self.calls: list[dict[str, Any]] = []

    def generate(self, prompt: str, system_instruction: str | None = None) -> str:
        self.calls.append({"prompt": prompt, "system_instruction": system_instruction})
        return self.response_text


